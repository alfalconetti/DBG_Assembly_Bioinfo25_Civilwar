class Contig:
    """
    Represents an assembled contig, and contains its sequence, graph topology
    metadata, and attributes used for statistical analysis.

    A Contig is generated by traversing a De Bruijn Graph. It can incorporate 
    resolved structural variants such as bubbles and tips. Each instance is 
    topologically classified into one of three primary categories:
    - Linear: A simple path with distinct start and end points.
    - Circular: A closed loop where the start and end nodes coincide.
    - Lariat: A 'lasso' structure where a linear 'tail' leads into a cycle, 
      often indicative of unresolved repeats or sequencing artifacts.

    The class supports additive composition via '__add__', merging sequences 
    (handling k-mer/edges overlaps) and consolidating topological metadata.
    
    :ivar seq: Assembled DNA sequence
    :type seq: str
    :ivar start_node: Node where the contig begins
    :type start_node: Node
    :ivar final_node: Node where the contig ends
    :type final_node: Node
    :ivar walk_weights: Coverage weights for each k-mer (edge) in the path
    :type walk_weights: list[int]
    :ivar receiving_hubs_visited: Set of receiving hub k-mers encountered
    :type receiving_hubs_visited: set[str]
    :ivar k: K-mer size
    :type k: int
    :ivar hub: Whether the contig traversed through a hub
    :type hub: bool
    :ivar bubble: Whether the contig includes a resolved bubble
    :type bubble: bool
    :ivar tip: Whether the contig includes an assembled tip
    :type tip: bool
    :ivar remaining: Whether from fork_in_hub residual processing
    :type remaining: bool
    :ivar from_catch_all: Whether from final circular/isolated search
    :type from_catch_all: bool
    :ivar tag: Topological classification tag
    :type tag: str
    :ivar branch_kmer: K-mer where lariat branches (for lariat structures)
    :type branch_kmer: str or None
    :ivar bubble_ends: (source_seq, dest_seq) of bubble if present
    :type bubble_ends: tuple[str, str]
    :ivar tip_hub: Hub k-mer where tip originated
    :type tip_hub: str or None
    :ivar hub_seq: K-mer of hub traversed
    :type hub_seq: str or None
    """
    def __init__(
        self,
        seq,
        start_node,
        final_node,
        walk_weights,
        receiving_hubs_visited,
        k,
        hub=False,
        bubble=False,
        tip=False,
        bubble_ends=(None, None),
        tip_hub=None,
        hub_seq=None,
        remaining=False,
        from_catch_all=False
    ):
        """
        Initializes a new Contig instance. 

        :param seq: The assembled DNA sequence string.
        :type seq: str
        :param start_node: The Node object where the path begins.
        :type start_node: Node
        :param final_node: The Node object where the path ends or gets interrupted.
        :type final_node: Node
        :param walk_weights: List of coverage values (multiplicities) for each edge traversed.
        :type walk_weights: list[int]
        :param receiving_hubs_visited: Set of k-mers corresponding to nodes with in-degree > 1 
                                       (convergence) encountered during the walk.
        :type receiving_hubs_visited: set[str]
        :param k: The k-mer size used for the assembly. Must be equal to the one of the graph from
                  which contigs are generated because it is necessary for adding logic
        :type k: int
        :param hub: Flag indicating if the contig was initiated or passed through a branching point. (fork_in_hub)
        :type hub: bool
        :param bubble: Flag indicating if the contig contains a resolved bubble (variant). (fork_in_hub)
        :type bubble: bool
        :param tip: Flag indicating if the contig includes a resolved tip (dead end). (fork_in_hub)
        :type tip: bool
        :param bubble_ends: Tuple containing (source_kmer, target_kmer) of a resolved bubble that was
                            retained in bubble processing but was solved in assembly. Should find matched variant.
        :type bubble_ends: tuple[str or None, str or None]
        :param tip_hub: The k-mer of the junction where a tip was attached in a tip that was retained in tip processing.
        :type tip_hub: str or None
        :param hub_seq: The k-mer of the primary (or secondary if also bubble) hub that generated this contig path.
        :type hub_seq: str or None
        :param remaining: True if the contig was generated during residual hub processing after fork_in_hub.
        :type remaining: bool
        :param from_catch_all: True if identified during the final search for isolated circular paths.
        :type from_catch_all: bool
        """
        self.seq = seq
        self.start_node = start_node
        self.final_node = final_node
        self.walk_weights = walk_weights
        self.receiving_hubs_visited = receiving_hubs_visited
        self.k = k
        self.bubble = bubble
        self.tip = tip
        self.hub = hub
        self.remaining = remaining
        self.from_catch_all = from_catch_all
        self.tag = ""
        self.branch_kmer = None
        self.bubble_ends = bubble_ends
        self.tip_hub = tip_hub
        self.hub_seq = hub_seq


    def __iadd__(self, other):
        """
        Extends the current contig by appending another contig in-place.
        
        The sequences are merged by overlapping the prefix of 'other' with the 
        suffix of 'self' using the k-1 overlap characteristic of de Bruijn graphs.
        Metadata, such as visited hubs and walk weights, are updated to reflect 
        the combined path.

        :param other: The contig to be appended to the current one.
        :type other: Contig
        :raises TypeError: If 'other' is not an instance of Contig.
        :return: The updated Contig instance.
        :rtype: Contig
        """
        if not isinstance(other, Contig):
            raise TypeError(f"You can't sum {type(self)} object with {type(other)}")
        self.seq += other.seq[self.k-1:] # Salto le prime k-1 basi del suffisso per evitare di duplicarle
        self.start_node = self.start_node
        self.final_node = other.final_node
        self.walk_weights += other.walk_weights
        self.receiving_hubs_visited = self.receiving_hubs_visited.union(other.receiving_hubs_visited)
        return self

    def __add__(self, other):
        """
        Concatenates two contigs into a new Contig instance.
        
        This method performs a deep merge of topological information. If either 
        contig contains a resolved variant (bubble, tip, or hub), the resulting 
        contig will inherit those flags with an OR logic. The junction point metadata 
        (bubble_ends, tip_hub) is prioritized from the second contig if 
        available, assuming a forward assembly direction using the sum between a 5' contig
        and a 3' contig.
        remaining and from_catch_all flags are not added because those objects should never be added

        :param other: The contig to be added to the right of the current one.
        :type other: Contig
        :raises TypeError: If 'other' is not an instance of Contig.
        :return: A new Contig instance representing the combined path.
        :rtype: Contig
        """
        if not isinstance(other, Contig):
            raise TypeError(f"You can't sum {type(self)} object with {type(other)}")
        if any(contig.remaining or contig.from_catch_all for contig in [self, other]):
            raise RuntimeError(f"Summing instances of contigs from remaining after fork_hub or from catch all search makes no sense")
        new = Contig(
            # Sequence merging con k-1 overlap
            seq=self.seq + other.seq[self.k-1:],
            start_node=self.start_node,
            final_node=other.final_node,
            # Metadata merging
            walk_weights=self.walk_weights + other.walk_weights,
            receiving_hubs_visited=self.receiving_hubs_visited.union(other.receiving_hubs_visited),
            k=self.k,
            # Le flag sono ereditate con OR
            bubble=self.bubble or other.bubble,
            tip = self.tip or other.tip,
            hub = self.hub or other.hub,
            # Le informazioni di sequenza preferibilmente dal secondo addendo
            bubble_ends = other.bubble_ends if other.bubble_ends != (None, None) else self.bubble_ends,
            tip_hub = other.tip_hub if other.tip_hub is not None else self.tip_hub,
            hub_seq = other.hub_seq if other.hub_seq is not None else self.hub_seq
        )
        return new

    def copy(self):
        """
        Creates a deep copy of the mutable attributes of the contig.
        
        Essential to prevent modifications to 'walk_weights' or 
        'receiving_hubs_visited' in a derived contig from affecting 
        the original instance during forking or path extension.
        """
        new = Contig(
            seq=self.seq, 
            start_node=self.start_node, 
            final_node=self.final_node, 
            walk_weights=list(self.walk_weights), 
            receiving_hubs_visited=set(self.receiving_hubs_visited), 
            k=self.k, 
            bubble=self.bubble, 
            tip=self.tip,
            hub=self.hub,
            bubble_ends=self.bubble_ends,
            tip_hub=self.tip_hub,
            hub_seq=self.hub_seq
        )
        new.tag = self.tag  
        new.branch_kmer = self.branch_kmer  
        return new

    @classmethod
    def from_walk_linear(cls, walk_result, k, initial_node, hub = False, hub_seq = None, remaining = False, from_catch_all = False):
        """
        Factory method that instantiates a Contig from the output of the 
        graph traversal linear method (_walk_linear).
        
        Makes easier interactions between the raw graph walking logic and the 
        structured Contig representation.
        """
        seq, final_node, weights, hubs = walk_result
        return cls(seq, initial_node, final_node, weights, hubs, k, hub = hub, hub_seq = hub_seq, remaining = remaining, from_catch_all = from_catch_all)

    def __len__(self):
        return len(self.seq)

    def __repr__(self):
        return f"Contig(len={len(self)}, tag={self.tag or 'untagged'})"
    
    def is_circular(self):
        """Checks if the path is a perfect closed loop (start == end)."""
        return self.start_node == self.final_node

    def is_lariat(self):
        """
        Detects a 'lasso' topology.
        
        A lariat is identified if the final node is a receiving hub already 
        encountered within the current path. The junction must be
        internal to this specific sequence and is immediately saved in the branch_kmer
        attribute
        """
        if self.is_circular():
            return False
        if self.final_node.seq in self.receiving_hubs_visited and self.final_node.seq in self.seq[:-1]:
            self.branch_kmer = self.final_node.seq
            return True
        else:
            return False

    def is_bubble_ending(self):
        """
        Determines if the contig terminates exactly at the convergence node 
        of a resolved bubble. Helps distinguish isolated variants from 
        paths that continue further.
        """
        return self.bubble and self.bubble_ends[1] == self.final_node.seq
    
    def get_fasta_header(self, contig_id):
        """
        Generates a standardized FASTA header string containing topological metadata.
        
        Features:
        - Median coverage calculation (more robust than mean against sequencing bias).
        - Conditional tags: branch (lariat), bubble_ends, tip_from, or hub_origin.
        - K-mer truncation to 10bp to ensure better readability
        """
        from statistics import median
        # Tutti i k-mer sono troncati a 10 bp
        median_cov = median(self.walk_weights) if self.walk_weights else 0
        header_parts = [
            f"contig_{contig_id}",
            f"len={len(self)}",
            f"tag={self.tag}",
            f"cov={median_cov:.1f}"
        ]

        # 2. Metadati topologici condizionali (solo se attinenti)
        if self.branch_kmer:
            header_parts.append(f"branch={self.branch_kmer}")
        
        if self.bubble_ends != (None, None):
            header_parts.append(f"bubble_ends={self.bubble_ends[0][:10]}..-{self.bubble_ends[1][:10]}..")
        
        if self.tip_hub:
            header_parts.append(f"tip_from={self.tip_hub[:10]}..")
            
        if self.hub_seq:
            header_parts.append(f"hub_origin={self.hub_seq[:10]}..")

        # Uniamo tutto con il pipe
        return ">" + "|".join(header_parts)

    def get_tag(self):
        """
        Assigns a highly granular topological classification tag to the contig.
        
        The method synthesizes structural flags (bubble, tip), origin context 
        (remaining, from_catch_all), and graph junctions to generate a 
        descriptive metadata tag.
        
        Key logic features:
        - Origin: Distinguishes between generic hub starts 
          ('_hub_starting') and specific bubble origins ('_bubble_starting').
        - Topological Hierarchy: Prioritizes Tips (that can only be linear), 
          then classifies between Circular paths, Lariats, and finally general
          Linear paths with granular sub-tagging for each.
        - Dynamic Suffixing: if the contig ends or starts in hub (or bubble) it 
          be flagged as so, 
          NOTE: Circular contigs are always assumed to start from hub except if 
          they are flagged as circular_isolated (the normal standalone structure
          which does not have a standard entry point).
        
        ALL TAGS ARE BETTER EXPLAINED IN THE PROJECT README

        :return: None. Updates the 'self.tag' attribute.
        """
        # ALL CIRCULAR NOT ISOLATED START FROM A HUB AND END IN HUB. RESIDUAL TUTTI START IN HUB
        if self.start_node.is_hub():
            if self.bubble and self.start_node.seq == self.bubble_ends[0]:
                hub_starting = "_bubble_starting"
            else:
                hub_starting = "_hub_starting"
        else:
            hub_starting = ""
        if self.final_node.is_hub():
            hub_ending = "_hub_ending"
        else:
            hub_ending = ""
        
        if self.tip:
            self.tag = "linear_with_tip"
            return # Se tip non servono altri controlli, solo lineare
        if self.is_circular(): # ALL CIRCULAR NOT ISOLATED START FROM A HUB
            # QUI NON SERVE HUB STARTING CHE È SCONTATO, IMPORTANTE SOLO SE DA BUBBLE
            if self.remaining:
                self.tag = "circular_fork_hub_residual"
            elif self.from_catch_all:
                self.tag = "circular_isolated"
            elif self.bubble:
                if self.is_bubble_ending():
                    self.tag = "circular_bubble_resolved_ending" + hub_starting
                else:
                    if self.hub:
                        self.tag = "circular_with_bubble_through_hub" + hub_starting
                    else:
                        self.tag = "circular_with_bubble" + hub_starting
            elif self.hub:
                self.tag = "circular_through_hub" 
            elif not self.hub and self.final_node.is_hub():
                self.tag = "circular_self_loop_hub" # parte e ritorna da hub
            else:
                self.tag = "unknown_circular_like"
        elif self.is_lariat():
            if self.remaining:
                self.tag = "lariat_fork_hub_residual" + hub_ending
            elif self.from_catch_all:
                self.tag = "unknown_lariat_like_from_catch_all" 
            elif self.bubble:
                if self.is_bubble_ending():
                    self.tag = "lariat_bubble_resolved_ending" + hub_starting
                else:
                    if self.hub:
                        self.tag = "lariat_with_bubble_through_hub" + hub_starting + hub_ending
                    else:
                        self.tag = "lariat_with_bubble" + hub_starting + hub_ending
            elif self.hub:
                self.tag = "lariat_through_hub" + hub_starting
            elif not self.hub and self.final_node.is_hub():
                self.tag = "lariat_branch_at_hub" + hub_starting
            elif not self.hub:
                self.tag = "lariat_simple" + hub_starting
            else:
                self.tag = "unknown_lariat_like" + hub_starting + hub_ending
        else:
            if self.remaining:
                self.tag = "linear_fork_hub_residual" + hub_ending
            elif self.from_catch_all:
                self.tag = "unknown_linear_like_from_catch_all"
            elif self.bubble:
                if self.is_bubble_ending():
                    self.tag = "linear_bubble_resolved_ending" + hub_starting + hub_ending
                else:
                    if self.hub:
                        self.tag = "linear_bubble_resolved_extended_through_hub" + hub_starting + hub_ending
                    elif self.start_node.seq == self.bubble_ends[0] and self.final_node.seq == self.bubble_ends[1]:
                        self.tag = "linear_bubble_branch_bubble_starting"
                    else:
                        self.tag = "linear_bubble_resolved_extended" + hub_starting + hub_ending
            elif not self.bubble and not self.tip and self.hub:
                self.tag = "linear_through_hub" + hub_starting + hub_ending
            elif not self.hub:
                self.tag = "linear_simple" + hub_starting + hub_ending
            else:
                self.tag = "unknown_linear_like" + hub_starting + hub_ending